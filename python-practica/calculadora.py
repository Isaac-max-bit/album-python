# Calculadora de cambio 

#1. Pedir el dinero entregado
dinero = float(input("Ingrese el dinero entregado: "))

#2. Pedir el costo del producto
costo = float(input("Ingrese el costo del producto: "))

#3. Calcular el cambio 
cambio = dinero - costo

#4. Mostrar el resultado
print("El cambio a devolver es: ", cambio)